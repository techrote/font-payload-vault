def _widen(spec, fx):
    """Scale every x coordinate of a skeleton path; used only for BLOCK punctuation."""
    out, n = [], 0
    for tok in spec.split():
        if tok in ('M', 'L', 'C', 'Z'):
            n = 0
            out.append(tok)
        else:
            out.append(str(round(float(tok) * fx, 1)) if n % 2 == 0 else tok)
            n += 1
    return ' '.join(out)


