def ribbon(g):
    # Border of a united solid, so intersections are resolved before hollowing.
    return g.difference(g.buffer(-36,quad_segs=12,join_style='round'))

def finish_shape(c,g,a):
    if g.is_empty:return g
    return fitted(affine_transform(ribbon(g),[1,SHEAR,0,1,0,0]),a,53)

