def draw():
    result = {' ': (Polygon(),ADVANCE)}
    for c,grid in GRIDS.items():
        rows = grid.split('/')
        if any(len(r)!=7 or set(r)-{'.','#'} for r in rows):
            raise ValueError(f'Invalid seven-column bitmap for {c!r}')
        # Two tearing rows per glyph; deterministic digest, no Python hash/RNG.
        digest = sha256(('cache-rattle-v1:'+c).encode('utf-8')).digest()
        tear = {2+digest[0]%3: -32, 5+digest[1]%3: 38}
        ink = []
        for y,row in enumerate(rows):
            # Horizontal scanline gaps (10u), 78u row pitch, 68u module width.
            for x,pixel in enumerate(row):
                if pixel == '#':
                    x0 = 92+x*68+tear.get(y,0)
                    y0 = 700-(y+1)*78
                    ink.append(box(x0,y0+10,x0+68,y0+78))
        result[c] = (merge(*ink),ADVANCE)
    assert set(result) == {chr(i) for i in range(32,127)}
    return result
