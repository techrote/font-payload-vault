def glyph(rows):
    parts = []
    for r, row in enumerate(rows):
        y = BASE_Y + (6 - r) * PITCH_Y
        for c, mark in enumerate(row):
            if mark == '#':
                x = ORIGIN_X + c * PITCH_X + DRIFT[r]
                parts.append(disc(x, y, DOT_RADIUS))
    return merge(*parts) if parts else Polygon()


def draw():
    out = {}
    for c in range(32, 127):
        ch = chr(c)
        key = ch.upper() if ch.islower() else ch
        out[ch] = (glyph(RASTER[key]), ADVANCE)
    assert set(out) == {chr(i) for i in range(32, 127)}
    return out
