def draw():
    if set(GRID)!=ASCII:raise ValueError('ASCII grid is incomplete')
    out={}
    for c,spec in GRID.items():
        cells=[]
        for row,line in enumerate(spec.split('/')):
            if len(line)!=6 or set(line)-set('.#') or row>11:raise ValueError((c,row,line))
            for col,v in enumerate(line):
                if v=='#':
                    x=135+90*col;y=700-80*row
                    # A filled emitter plus a separate thin halo, all monochrome.
                    cells.append(merge(disc(x,y,25),disc(x,y,38).difference(disc(x,y,31))))
        out[c]=(clean(merge(*cells)),ADVANCE)
    return out
