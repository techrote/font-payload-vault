def finalize(c,g,a):
    """Accent composition sees the positive cutter, not an already inverted tile."""
    if c in (' ','\u00a0') or c in '─│┌┐└┘├┤┬┴┼█▀▄▌▐░▒▓←↑→↓↔■□▲▶▼◀✓✕':return g
    cutter=fitted(g,a,86)
    x0,y0,x1,y1=cutter.bounds
    if y1>930 or y0<-202:
        # Only very tall accent/punctuation cutters need this whole-glyph fit.
        factor=min(1,1132/(y1-y0))
        cutter=scale(cutter,xfact=1,yfact=factor,origin=(0,0))
        y0,y1=cutter.bounds[1],cutter.bounds[3]
        cutter=translate(cutter,yoff=min(0,930-y1)+max(0,-202-y0))
    tile=chamfer(27,-242,a-27,992,38)
    tile=tile.difference(merge(box(20,313,57,395),box(a-57,313,a-20,395)))
    return clean(tile.difference(cutter))
